"""
plots.py — the evaluation figures for the report (Problems 5 and 6).

Every function draws one figure, saves it as a vector PDF into
report/figures/ (git-ignored, regenerated by `python -m src.run_all`) and
returns the path. The data-exploration figures (Figures 1-4) live in src/eda.py.
"""

from __future__ import annotations

import os

import matplotlib

matplotlib.use("Agg")  # no display needed; must come before pyplot
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from . import evaluate  # noqa: E402

FIGURES_DIR = "report/figures"


def _save(fig, out_dir: str, name: str) -> str:
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, name)
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)
    return path


def predicted_vs_actual(log_true, preds: dict, out_dir: str = FIGURES_DIR,
                        name: str = "eval_pred_vs_actual.pdf") -> str:
    """Task A: predicted vs actual price (log-log), one panel per model."""
    n = len(preds)
    fig, axes = plt.subplots(1, n, figsize=(3.4 * n, 3.3), squeeze=False, sharey=True)
    log_true = np.asarray(log_true, dtype=float)
    lo, hi = np.percentile(log_true, [0.5, 99.5])
    for ax, (model, log_pred) in zip(axes[0], preds.items(), strict=True):
        ax.hexbin(log_true, np.asarray(log_pred, dtype=float), gridsize=45, bins="log",
                  extent=(lo, hi, lo, hi), cmap="Blues", mincnt=1)
        ax.plot([lo, hi], [lo, hi], color="black", lw=0.8, ls="--")
        rmse = evaluate.rmse(log_true, log_pred)
        ax.set_title(f"{model}\nRMSE(log) = {rmse:.3f}", fontsize=9)
        ax.set_xlabel("actual log(price)")
        ax.set_xlim(lo, hi)
        ax.set_ylim(lo, hi)
    axes[0][0].set_ylabel("predicted log(price)")
    fig.suptitle("Task A: predicted vs actual price on the test set", y=1.04)
    return _save(fig, out_dir, name)


def error_by_group(tables: dict, metric: str, title: str, ylabel: str,
                   out_dir: str = FIGURES_DIR, name: str = "eval_error_by_group.pdf") -> str:
    """Grouped bars: `metric` per group (x axis) for each model.

    tables = {model name: DataFrame with columns "group", "n" and `metric`}
    (the output of error_analysis.regression_breakdown / classification_breakdown).
    """
    models = list(tables)
    groups = list(next(iter(tables.values()))["group"])
    width = 0.8 / max(1, len(models))
    x = np.arange(len(groups))
    fig, ax = plt.subplots(figsize=(max(5.0, 0.9 * len(groups) + 2), 3.3))
    for i, model in enumerate(models):
        values = tables[model].set_index("group").reindex(groups)[metric].to_numpy()
        ax.bar(x + (i - (len(models) - 1) / 2) * width, values, width, label=model)
    counts = tables[models[0]].set_index("group").reindex(groups)["n"].to_numpy()
    ax.set_xticks(x, [f"{g}\n(n={c:,})" for g, c in zip(groups, counts, strict=True)], fontsize=7)
    ax.set_ylabel(ylabel)
    ax.set_title(title, fontsize=10)
    ax.legend(fontsize=7, frameon=False)
    ax.grid(axis="y", alpha=0.3)
    return _save(fig, out_dir, name)


def confusion_matrices(results: dict, out_dir: str = FIGURES_DIR,
                       name: str = "eval_confusion_matrices.pdf") -> str:
    """Task B: one 2x2 confusion matrix per classifier (rows = truth, columns = prediction)."""
    n = len(results)
    fig, axes = plt.subplots(1, n, figsize=(2.6 * n, 2.7), squeeze=False)
    for ax, (model, (y_true, y_pred)) in zip(axes[0], results.items(), strict=True):
        cm = evaluate.confusion_matrix(y_true, y_pred)
        ax.imshow(cm, cmap="Blues")
        for (i, j), value in np.ndenumerate(cm):
            ax.text(j, i, f"{value:,}", ha="center", va="center",
                    color="white" if value > cm.max() / 2 else "black", fontsize=9)
        ax.set_xticks([0, 1], ["standard", "premium"], fontsize=8)
        ax.set_yticks([0, 1], ["standard", "premium"], fontsize=8)
        ax.set_xlabel("predicted")
        ax.set_title(model, fontsize=9)
    axes[0][0].set_ylabel("actual")
    return _save(fig, out_dir, name)


def roc_curves(scores: dict, y_true, out_dir: str = FIGURES_DIR,
               name: str = "eval_roc_curves.pdf") -> str:
    """Task B: ROC curves of every classifier that produces continuous scores."""
    fig, ax = plt.subplots(figsize=(3.6, 3.4))
    for model, s in scores.items():
        fpr, tpr, _ = evaluate.roc_curve(y_true, s)
        ax.plot(fpr, tpr, lw=1.2, label=f"{model} (AUC {evaluate.roc_auc(y_true, s):.3f})")
    ax.plot([0, 1], [0, 1], color="gray", lw=0.8, ls="--")
    ax.set_xlabel("false-positive rate")
    ax.set_ylabel("true-positive rate")
    ax.set_title("Task B: ROC curves (test set)", fontsize=10)
    ax.legend(fontsize=6.5, frameon=False, loc="lower right")
    return _save(fig, out_dir, name)


def importance_bars(tables: dict, value: str = "importance", top: int = 12,
                    title: str = "Feature importance", out_dir: str = FIGURES_DIR,
                    name: str = "eval_feature_importance.pdf", xlabel=None) -> str:
    """Horizontal bars, one panel per table ({panel title: DataFrame with "feature" and `value`}).

    xlabel: one axis label for every panel, or a function panel title -> label
    (panels can have different units, e.g. RMSE for Task A and F1 for Task B).
    """
    n = len(tables)
    fig, axes = plt.subplots(1, n, figsize=(3.6 * n, 0.28 * top + 1.2), squeeze=False)
    for ax, (panel, table) in zip(axes[0], tables.items(), strict=True):
        part = table.head(top).iloc[::-1]
        colors = ["tab:red" if v < 0 else "tab:blue" for v in part[value]]
        ax.barh(part["feature"].astype(str), part[value], color=colors)
        ax.axvline(0, color="black", lw=0.6)
        ax.set_title(panel, fontsize=9)
        ax.tick_params(axis="y", labelsize=7)
        label = xlabel(panel) if callable(xlabel) else xlabel
        if label:
            ax.set_xlabel(label, fontsize=8)
    fig.suptitle(title, y=1.02)
    return _save(fig, out_dir, name)


def fit_time_scaling(rows: list[dict], out_dir: str = FIGURES_DIR,
                     name: str = "eval_fit_time_scaling.pdf") -> str:
    """Fit time vs number of training rows, log-log, one line per model.

    rows = [{"model": ..., "n_train": ..., "fit_seconds": ...}, ...]
    """
    fig, ax = plt.subplots(figsize=(4.0, 3.2))
    for model in dict.fromkeys(r["model"] for r in rows):
        pts = sorted((r["n_train"], r["fit_seconds"]) for r in rows if r["model"] == model)
        ax.plot(*zip(*pts, strict=True), marker="o", ms=3, lw=1.2, label=model)
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel("training rows")
    ax.set_ylabel("fit time (s)")
    ax.set_title("Fit time vs training-set size", fontsize=10)
    ax.legend(fontsize=6.5, frameon=False)
    ax.grid(alpha=0.3, which="both")
    return _save(fig, out_dir, name)
